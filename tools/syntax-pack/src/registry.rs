use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Component, Path, PathBuf};
use std::process::Command;
use std::sync::Mutex;
use std::sync::atomic::{AtomicUsize, Ordering};

use serde::Deserialize;
use serde_json::Value;

use crate::lock::{Grammar, Lock, Registry, RegistryRef, Scanner, Source};
use crate::{HOST, Options, build, check_language, fetch, inputs, sha256, source_hash};

pub const REGISTRY_URL: &str = "https://raw.githubusercontent.com/neovim-treesitter/treesitter-parser-registry/main/registry.json";

struct Upstream {
    url: String,
    semver: bool,
}

enum Kind {
    Grammar {
        parser: Upstream,
        queries: Upstream,
        location: Option<String>,
        self_contained: bool,
    },
    Queries(Upstream),
}

struct Entry {
    name: String,
    filetypes: Vec<String>,
    kind: Kind,
}

#[derive(Deserialize)]
struct ParserPin {
    url: Option<String>,
    parser_version: Option<String>,
}

pub fn generate(core: &Lock, options: &Options) -> Result<(), String> {
    let path = options
        .registry
        .as_deref()
        .ok_or("registry needs --registry FILE, the registry.json to pin")?;
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    let json: Value = serde_json::from_str(&text).map_err(|e| format!("registry: {e}"))?;
    let extensions_path = options
        .extensions
        .clone()
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("extensions.toml"));
    let extensions: BTreeMap<String, Vec<String>> = toml::from_str(
        &fs::read_to_string(&extensions_path)
            .map_err(|e| format!("{}: {e}", extensions_path.display()))?,
    )
    .map_err(|e| format!("{}: {e}", extensions_path.display()))?;

    let entries = parse_registry(&json)?;
    let core_tags: BTreeMap<&str, &str> = core
        .grammars
        .iter()
        .filter(|(language, _)| core.is_core(language))
        .flat_map(|(language, grammar)| {
            grammar
                .aliases
                .iter()
                .chain(&grammar.extensions)
                .map(move |tag| (tag.as_str(), language.as_str()))
        })
        .collect();
    let wanted: Vec<&Entry> = entries
        .iter()
        .filter(|entry| options.languages.is_empty() || options.languages.contains(&entry.name))
        .collect();
    eprintln!("resolving the queries of {} entries", entries.len());
    let queries: BTreeMap<String, Source> = par_map(&entries, options.jobs, |entry| {
        let upstream = match &entry.kind {
            Kind::Grammar { queries, .. } => queries,
            Kind::Queries(queries) => queries,
        };
        resolve(upstream).map(|source| (entry.name.clone(), source))
    })
    .into_iter()
    .filter_map(|resolved| resolved.map_err(|error| eprintln!("warning: {error}")).ok())
    .collect();

    let built = par_map(&wanted, options.jobs, |entry| {
        if core.is_core(&entry.name) {
            return None;
        }
        let Kind::Grammar { .. } = entry.kind else {
            return None;
        };
        if let Some(owner) = core_tags.get(entry.name.as_str()) {
            return Some((entry.name.clone(), Err(format!("{owner} claims the tag"))));
        }
        eprintln!("checking {}", entry.name);
        Some((entry.name.clone(), grammar_for(entry, &queries, options)))
    });

    let mut out = Registry {
        registry: Some(RegistryRef {
            url: REGISTRY_URL.to_owned(),
            rev: sha256(text.as_bytes()),
        }),
        ..Registry::default()
    };
    let mut used = BTreeSet::new();
    for (name, result) in built.into_iter().flatten() {
        match result {
            Ok((grammar, fragments)) => {
                used.extend(fragments);
                out.language.insert(name, grammar);
            }
            Err(error) => {
                eprintln!("skipping {name}: {error}");
                out.skipped.insert(name, error);
            }
        }
    }
    for entry in &entries {
        if let Kind::Queries(_) = entry.kind
            && !out.language.contains_key(&entry.name)
        {
            out.skipped
                .entry(entry.name.clone())
                .or_insert_with(|| "queries only".to_owned());
        }
    }
    for name in used {
        if let Some(source) = queries.get(&name) {
            out.fragment.insert(name, source.clone());
        }
    }
    assign_tags(core, &entries, &extensions, &mut out);

    let write = Path::new(env!("CARGO_MANIFEST_DIR")).join("registry.toml");
    let toml = toml::to_string_pretty(&out).map_err(|e| e.to_string())?;
    let header = "# Generated by `syntax-pack registry` from the nvim-treesitter parser\n\
                  # registry and extensions.toml; regenerate rather than edit.\n\n";
    fs::write(&write, format!("{header}{toml}"))
        .map_err(|e| format!("{}: {e}", write.display()))?;
    println!(
        "{}: {} languages, {} skipped",
        write.display(),
        out.language.len(),
        out.skipped.len()
    );
    Ok(())
}

fn parse_registry(json: &Value) -> Result<Vec<Entry>, String> {
    let object = json.as_object().ok_or("registry: not an object")?;
    let mut entries = Vec::new();
    for (name, value) in object {
        if name.starts_with('$') || !value.is_object() {
            continue;
        }
        let source = &value["source"];
        let string = |key: &str| source[key].as_str().map(str::to_owned);
        let flag = |key: &str| source[key].as_bool().unwrap_or(false);
        let kind = match source["type"].as_str() {
            Some("queries_only") => match string("queries_url").or_else(|| string("url")) {
                Some(url) => Kind::Queries(Upstream {
                    url,
                    semver: flag("queries_semver") || flag("semver"),
                }),
                None => continue,
            },
            Some("self_contained") => {
                let Some(url) = string("url") else { continue };
                Kind::Grammar {
                    parser: Upstream {
                        url: url.clone(),
                        semver: flag("semver"),
                    },
                    queries: Upstream {
                        url,
                        semver: flag("semver"),
                    },
                    location: string("parser_location"),
                    self_contained: true,
                }
            }
            _ => {
                let (Some(parser), Some(queries)) = (string("parser_url"), string("queries_url"))
                else {
                    continue;
                };
                Kind::Grammar {
                    parser: Upstream {
                        url: parser,
                        semver: flag("parser_semver"),
                    },
                    queries: Upstream {
                        url: queries,
                        semver: flag("queries_semver"),
                    },
                    location: string("parser_location"),
                    self_contained: false,
                }
            }
        };
        let filetypes = value["filetypes"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|v| v.as_str().map(str::to_ascii_lowercase))
            .collect();
        entries.push(Entry {
            name: name.clone(),
            filetypes,
            kind,
        });
    }
    Ok(entries)
}

fn resolve(upstream: &Upstream) -> Result<Source, String> {
    let rev = if upstream.semver {
        match newest_tag(&upstream.url)? {
            Some((_, commit)) => commit,
            None => head(&upstream.url)?,
        }
    } else {
        head(&upstream.url)?
    };
    Ok(Source {
        repo: upstream.url.clone(),
        rev,
    })
}

fn ls_remote(url: &str, args: &[&str]) -> Result<String, String> {
    let output = Command::new("git")
        .arg("ls-remote")
        .args(args)
        .arg(url)
        .env("GIT_TERMINAL_PROMPT", "0")
        .output()
        .map_err(|e| format!("git: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "git ls-remote {url}: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

fn head(url: &str) -> Result<String, String> {
    ls_remote(url, &[])?
        .lines()
        .find_map(|line| line.strip_suffix("\tHEAD"))
        .map(str::to_owned)
        .ok_or_else(|| format!("{url} has no HEAD"))
}

fn tags(url: &str) -> Result<BTreeMap<String, String>, String> {
    let mut tags = BTreeMap::new();
    for line in ls_remote(url, &["--tags"])?.lines() {
        let Some((commit, name)) = line.split_once('\t') else {
            continue;
        };
        let Some(name) = name.strip_prefix("refs/tags/") else {
            continue;
        };
        match name.strip_suffix("^{}") {
            Some(tag) => {
                tags.insert(tag.to_owned(), commit.to_owned());
            }
            None => {
                tags.entry(name.to_owned())
                    .or_insert_with(|| commit.to_owned());
            }
        }
    }
    Ok(tags)
}

fn semver(tag: &str) -> Option<(u64, u64, u64)> {
    let mut parts = tag.strip_prefix('v').unwrap_or(tag).split('.');
    let version = (
        parts.next()?.parse().ok()?,
        parts.next()?.parse().ok()?,
        parts.next()?.parse().ok()?,
    );
    parts.next().is_none().then_some(version)
}

fn newest_tag(url: &str) -> Result<Option<(String, String)>, String> {
    Ok(tags(url)?
        .into_iter()
        .filter_map(|(tag, commit)| semver(&tag).map(|version| (version, tag, commit)))
        .max()
        .map(|(_, tag, commit)| (tag, commit)))
}

fn is_commit(rev: &str) -> bool {
    rev.len() == 40 && rev.bytes().all(|b| b.is_ascii_hexdigit())
}

fn parser_source(
    parser: &Upstream,
    queries_dir: &Path,
    self_contained: bool,
    queries: &Source,
) -> Result<Source, String> {
    if self_contained {
        return Ok(queries.clone());
    }
    let pin: Option<ParserPin> = fs::read(queries_dir.join("parser.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice(&bytes).ok());
    let url = pin
        .as_ref()
        .and_then(|pin| pin.url.clone())
        .unwrap_or_else(|| parser.url.clone());
    match pin.and_then(|pin| pin.parser_version) {
        Some(rev) if is_commit(&rev) => Ok(Source { repo: url, rev }),
        Some(tag) => {
            let commit = tags(&url)?
                .remove(&tag)
                .ok_or_else(|| format!("{url} has no tag {tag}"))?;
            Ok(Source {
                repo: url,
                rev: commit,
            })
        }
        None => resolve(&Upstream {
            url,
            semver: parser.semver,
        }),
    }
}

fn grammar_for(
    entry: &Entry,
    queries: &BTreeMap<String, Source>,
    options: &Options,
) -> Result<(Grammar, BTreeSet<String>), String> {
    let Kind::Grammar {
        parser,
        location,
        self_contained,
        ..
    } = &entry.kind
    else {
        return Err("queries only".to_owned());
    };
    let name = &entry.name;
    let query_source = queries
        .get(name)
        .ok_or("its query repository did not resolve")?;
    let queries_dir = fetch(&format!("{name}-queries"), query_source, options)?;
    let parser_source = parser_source(parser, &queries_dir, *self_contained, query_source)?;
    let root = fetch(name, &parser_source, options)?;
    let src = match location {
        Some(location) => format!("{}/src", location.trim_end_matches('/')),
        None => "src".to_owned(),
    };
    let src_dir = root.join(&src);
    let generate = !src_dir.join("parser.c").is_file();
    if generate && !src_dir.join("grammar.json").is_file() {
        return Err("no parser.c or grammar.json".to_owned());
    }
    let scanner = if src_dir.join("scanner.c").is_file() {
        Scanner::C
    } else if src_dir.join("scanner.cc").is_file() {
        Scanner::Cc
    } else {
        Scanner::None
    };

    let (query_root, prefix) = if *self_contained {
        (root.clone(), "")
    } else {
        (queries_dir.clone(), "q:")
    };
    let own = |file: &str| -> Option<String> {
        find_query(&query_root, file).map(|path| format!("{prefix}{path}"))
    };
    let highlights_file = own("highlights.scm").ok_or("no highlights.scm")?;
    let injections_file = own("injections.scm");
    let locals_file = own("locals.scm");
    let mut fragments = BTreeSet::new();
    let read = |input: &str| -> String {
        let path = input.strip_prefix("q:").unwrap_or(input);
        fs::read_to_string(query_root.join(path)).unwrap_or_default()
    };
    let mut highlights = Vec::new();
    inherit(
        &read(&highlights_file),
        "highlights.scm",
        queries,
        options,
        &mut BTreeSet::from([name.clone()]),
        &mut fragments,
        &mut highlights,
    )?;
    highlights.push(highlights_file);
    let mut injections = Vec::new();
    if let Some(file) = injections_file {
        inherit(
            &read(&file),
            "injections.scm",
            queries,
            options,
            &mut BTreeSet::from([name.clone()]),
            &mut fragments,
            &mut injections,
        )?;
        injections.push(file);
    }
    let mut locals = Vec::new();
    if let Some(file) = locals_file {
        inherit(
            &read(&file),
            "locals.scm",
            queries,
            options,
            &mut BTreeSet::from([name.clone()]),
            &mut fragments,
            &mut locals,
        )?;
        locals.push(file);
    }

    let sample = if *self_contained {
        None
    } else {
        first_file(&queries_dir.join("tests/highlights"))
            .map(|file| format!("q:tests/highlights/{file}"))
    };
    let version = format!("{}+{}", &parser_source.rev[..12], &query_source.rev[..12]);
    let mut grammar = Grammar {
        repo: parser_source.repo.clone(),
        rev: parser_source.rev.clone(),
        version,
        src: src.clone(),
        symbol: None,
        queries: (!*self_contained).then(|| query_source.clone()),
        include: outside_includes(&root, &src)?,
        aliases: Vec::new(),
        extensions: Vec::new(),
        highlights,
        injections,
        locals,
        sha256: String::new(),
        license: license(&root),
        scanner,
        generate,
        sample,
        captures: Vec::new(),
        injects: Vec::new(),
    };

    let lock = Lock {
        grammars: BTreeMap::from([(name.clone(), grammar.clone())]),
        fragments: fragments
            .iter()
            .filter_map(|f| queries.get(f).map(|s| (f.clone(), s.clone())))
            .collect(),
        core: BTreeSet::new(),
    };
    grammar.sha256 = source_hash(&inputs(&lock, name, options)?)?;
    let mut lock = lock;
    lock.grammars.insert(name.clone(), grammar.clone());
    let check = Options {
        languages: vec![name.clone()],
        target: HOST.to_owned(),
        out: options.work.join("registry-check"),
        work: options.work.clone(),
        sources: None,
        base_url: None,
        key: None,
        index_url: None,
        registry: None,
        extensions: None,
        jobs: 1,
    };
    build(&lock, name, &check)?;
    check_language(&lock, name, &check)?;
    Ok((grammar, fragments))
}

fn inherit(
    query: &str,
    file: &str,
    queries: &BTreeMap<String, Source>,
    options: &Options,
    seen: &mut BTreeSet<String>,
    fragments: &mut BTreeSet<String>,
    out: &mut Vec<String>,
) -> Result<(), String> {
    let names: Vec<String> = query
        .lines()
        .take_while(|line| line.trim_start().starts_with(';') || line.trim().is_empty())
        .filter_map(|line| line.trim_start().strip_prefix("; inherits:"))
        .flat_map(|names| names.split(','))
        .map(|name| name.trim().trim_matches(['(', ')']).to_owned())
        .filter(|name| !name.is_empty())
        .collect();
    for name in names {
        if !seen.insert(name.clone()) {
            continue;
        }
        let Some(source) = queries.get(&name) else {
            return Err(format!("inherits {name}, which has no query repository"));
        };
        let dir = fetch(&format!("{name}-queries"), source, options)?;
        let Some(path) = find_query(&dir, file) else {
            continue;
        };
        let text = fs::read_to_string(dir.join(&path)).unwrap_or_default();
        inherit(&text, file, queries, options, seen, fragments, out)?;
        fragments.insert(name.clone());
        out.push(format!("@{name}:q/{path}"));
    }
    Ok(())
}

fn find_query(root: &Path, file: &str) -> Option<String> {
    let direct = Path::new("queries").join(file);
    if root.join(&direct).is_file() {
        return Some(format!("queries/{file}"));
    }
    let mut found = Vec::new();
    let mut stack = vec![PathBuf::new()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(root.join(&dir)) else {
            continue;
        };
        for entry in entries.flatten() {
            let rel = dir.join(entry.file_name());
            if entry.file_name() == ".git" {
                continue;
            }
            if entry.path().is_dir() {
                stack.push(rel);
            } else if entry.file_name() == file {
                found.push(rel.to_string_lossy().replace('\\', "/"));
            }
        }
    }
    found.sort_by_key(|path| (!path.ends_with(&format!("queries/{file}")), path.len()));
    found.into_iter().next()
}

fn first_file(dir: &Path) -> Option<String> {
    let mut files: Vec<String> = fs::read_dir(dir)
        .ok()?
        .flatten()
        .filter(|entry| entry.path().is_file())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .collect();
    files.sort();
    files.into_iter().next()
}

fn outside_includes(root: &Path, src: &str) -> Result<Vec<String>, String> {
    let src_dir = root.join(src);
    let mut found = BTreeSet::new();
    let mut stack = vec![src_dir.clone()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
                continue;
            }
            if !path
                .extension()
                .is_some_and(|ext| ext == "c" || ext == "h" || ext == "cc")
            {
                continue;
            }
            let text = fs::read_to_string(&path).unwrap_or_default();
            for line in text.lines() {
                let Some(include) = line
                    .trim_start()
                    .strip_prefix("#include")
                    .map(str::trim)
                    .and_then(|rest| rest.strip_prefix('"'))
                    .and_then(|rest| rest.split('"').next())
                else {
                    continue;
                };
                let target = normalize(&path.parent().unwrap_or(&dir).join(include));
                if target.starts_with(&src_dir) || !target.starts_with(root) || !target.is_file() {
                    continue;
                }
                if let Ok(rel) = target.strip_prefix(root) {
                    found.insert(rel.to_string_lossy().replace('\\', "/"));
                }
            }
        }
    }
    Ok(found.into_iter().collect())
}

fn normalize(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::ParentDir => {
                out.pop();
            }
            Component::CurDir => {}
            other => out.push(other),
        }
    }
    out
}

fn license(root: &Path) -> Option<String> {
    let json = |file: &str| -> Option<Value> {
        serde_json::from_slice(&fs::read(root.join(file)).ok()?).ok()
    };
    if let Some(license) =
        json("tree-sitter.json").and_then(|v| v["metadata"]["license"].as_str().map(str::to_owned))
    {
        return Some(license);
    }
    if let Some(license) =
        json("package.json").and_then(|v| v["license"].as_str().map(str::to_owned))
    {
        return Some(license);
    }
    let cargo: toml::Value =
        toml::from_str(&fs::read_to_string(root.join("Cargo.toml")).ok()?).ok()?;
    cargo
        .get("package")?
        .get("license")
        .and_then(|v| v.as_str())
        .map(str::to_owned)
}

fn assign_tags(
    core: &Lock,
    entries: &[Entry],
    extensions: &BTreeMap<String, Vec<String>>,
    out: &mut Registry,
) {
    let mut owners: BTreeMap<String, String> = BTreeMap::new();
    for (language, grammar) in core.grammars.iter().filter(|(l, _)| core.is_core(l)) {
        for tag in std::iter::once(language)
            .chain(&grammar.aliases)
            .chain(&grammar.extensions)
        {
            owners.insert(tag.clone(), language.clone());
        }
    }
    for language in out.language.keys() {
        owners
            .entry(language.clone())
            .or_insert_with(|| language.clone());
    }
    let valid = |tag: &str| {
        tag == tag.to_ascii_lowercase() && diffy_syntax::LanguageId::from_fence(tag).is_some()
    };
    let mut claim = |language: &str, tag: &str| -> bool {
        if !valid(tag) {
            return false;
        }
        match owners.get(tag) {
            Some(owner) => owner == language,
            None => {
                owners.insert(tag.to_owned(), language.to_owned());
                true
            }
        }
    };
    let names: Vec<String> = out.language.keys().cloned().collect();
    for language in &names {
        let tags: Vec<String> = extensions
            .get(language)
            .into_iter()
            .flatten()
            .filter(|tag| tag.as_str() != language && claim(language, tag))
            .cloned()
            .collect();
        if let Some(grammar) = out.language.get_mut(language) {
            grammar.extensions = tags;
        }
    }
    for entry in entries {
        let Some(grammar) = out.language.get(&entry.name) else {
            continue;
        };
        let taken = grammar.extensions.clone();
        let aliases: Vec<String> = entry
            .filetypes
            .iter()
            .filter(|tag| **tag != entry.name && !taken.contains(tag))
            .filter(|tag| claim(&entry.name, tag))
            .cloned()
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect();
        if let Some(grammar) = out.language.get_mut(&entry.name) {
            grammar.aliases = aliases;
        }
    }
}

pub fn par_map<T: Sync, R: Send>(items: &[T], jobs: usize, f: impl Fn(&T) -> R + Sync) -> Vec<R> {
    let next = AtomicUsize::new(0);
    let results: Mutex<Vec<Option<R>>> = Mutex::new((0..items.len()).map(|_| None).collect());
    std::thread::scope(|scope| {
        for _ in 0..jobs.max(1).min(items.len().max(1)) {
            scope.spawn(|| {
                loop {
                    let i = next.fetch_add(1, Ordering::Relaxed);
                    let Some(item) = items.get(i) else { break };
                    let result = f(item);
                    if let Ok(mut results) = results.lock() {
                        results[i] = Some(result);
                    }
                }
            });
        }
    });
    results
        .into_inner()
        .unwrap_or_default()
        .into_iter()
        .flatten()
        .collect()
}
